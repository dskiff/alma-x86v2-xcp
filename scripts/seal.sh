#!/bin/bash
# Seal the image: remove everything specific to this build VM so every clone
# starts clean. This must be the last provisioner: the first boot, Packer's SSH
# session and the CIS scan all create per-instance state.
set -euxo pipefail

# The CIS scan sets a 365-day maximum age and a 45-day INACTIVE period on every
# account with a password, overriding the kickstart's "don't expire". Once the
# password expires, key-based SSH fails too ("Password change required but no
# TTY available"), locking ansible out. Restore "never expires".
chage -M -1 -I -1 -E -1 ansible

# Machine identity. An empty machine-id makes systemd generate a new one on the
# first boot; "uninitialized" (cloud-init clean --machine-id) would also mark it
# as a first boot and re-apply unit presets, undoing the kickstart's choices.
truncate -s 0 /etc/machine-id
if [[ -f /var/lib/dbus/machine-id && ! -L /var/lib/dbus/machine-id ]]; then
  rm -f /var/lib/dbus/machine-id
fi
rm -f /var/lib/systemd/random-seed
# cloud-init (or sshd-keygen) generates new host keys on each clone's first boot.
# Overwrite the build's keys before deleting them: the fstrim below can leave a
# small deleted file's data in the image (see there).
find /etc/ssh -maxdepth 1 -name 'ssh_host_*' -type f \
  -exec shred --iterations=0 --zero --remove {} +

# Build-time state.
cloud-init clean --logs --seed
# The CIS scan builds an AIDE baseline mid-build. It would be stale on every
# clone, so each VM should run `aide --init` once it is configured.
rm -f /var/lib/aide/aide.db.gz /var/lib/aide/aide.db.new.gz
# Kickstart copies and installer logs.
rm -rf /root/anaconda-ks.cfg /root/original-ks.cfg /root/anaconda-post.log /var/log/anaconda
dnf clean all
# dnf's transaction history and its countme markers record when the build ran.
rm -f /var/lib/dnf/history.sqlite* /var/lib/dnf/repos/*/countme
journalctl --rotate
journalctl --vacuum-time=1s
find /var/log -type f -not -path '/var/log/journal/*' -exec truncate -s 0 {} +

# Identities that every clone would otherwise share, and that differ between
# two builds. The network profile Anaconda wrote for the build VM carries its
# own UUID; a clone gets its network from cloud-init, or NetworkManager's
# default DHCP profile for each interface. The NVMe host ID and NQN are only
# used to connect to NVMe-oF targets, and nvme-cli generates new ones when
# asked to.
rm -f /etc/NetworkManager/system-connections/*.nmconnection
rm -f /etc/nvme/hostid /etc/nvme/hostnqn
rm -rf /root/.gnupg

# Caches the build filled, which are rebuilt when needed.
rm -f /var/cache/ldconfig/aux-cache
if [[ -d /var/cache/man ]]; then find /var/cache/man -mindepth 1 -delete; fi

# The CIS remediation backs up the authselect profile into timestamped
# directories on each change. The profile in use is unaffected.
if [[ -d /var/lib/authselect/backups ]]; then find /var/lib/authselect/backups -mindepth 1 -delete; fi

# LVM's metadata backups and archives record the time and the commands the
# install ran; LVM writes new ones the next time the metadata changes.
find /etc/lvm/archive /etc/lvm/backup -maxdepth 1 -type f -delete

# Build times written into generated files' header comments. They're
# rewritten to the newest package's build time (as in collect-evidence.sh),
# in the same format, so the files still parse as their tools expect.
newest_build=$(rpm -qa --qf '%{BUILDTIME}\n' | sort -n | tail -n 1)
stamp=$(LC_ALL=C TZ=UTC date -d "@${newest_build}" '+%a %b %e %H:%M:%S %Y')
# (grep exits 1 when no file has the header, as on AlmaLinux 10.)
{ grep -rlZ '^# Generated by authselect on ' /etc/authselect /var/lib/authselect || [[ $? -eq 1 ]]; } |
  xargs -0 -r sed -i "s/^# Generated by authselect on .*/# Generated by authselect on ${stamp}/"
sed -i "s/^# Created by anaconda on .*/# Created by anaconda on ${stamp}/" /etc/fstab
if [[ -f /etc/lvm/devices/system.devices ]]; then
  sed -i -E "s/^# Created by LVM command (\S+) pid [0-9]+ at .*/# Created by LVM command \1 at ${stamp}/" \
    /etc/lvm/devices/system.devices
fi

# The Java trust store records when each certificate was added. Extract it
# again with those times set to the same build time.
SOURCE_DATE_EPOCH="${newest_build}" update-ca-trust extract

# Boot entries are named after the build VM's machine ID, which differs on
# every build (and which the truncate above already discarded). Rename them
# to a fixed ID, the same for every build of this release. A clone's own
# machine ID names the entries of kernels it installs later.
# shellcheck source=/dev/null
. /etc/os-release
token=$(printf '%s' "${ID}-${VERSION_ID%%.*}-boot-entry" | sha256sum | cut -c1-32)
for entry in /boot/loader/entries/*.conf; do
  name=${entry##*/}
  if [[ "${name}" =~ ^[0-9a-f]{32}-(.+)$ ]]; then
    mv "${entry}" "/boot/loader/entries/${token}-${BASH_REMATCH[1]}"
  fi
done
saved=$(grub2-editenv - list | sed -n 's/^saved_entry=//p')
if [[ "${saved}" =~ ^[0-9a-f]{32}-(.+)$ ]]; then
  grub2-editenv - set "saved_entry=${token}-${BASH_REMATCH[1]}"
fi
grub2-editenv - list
ls /boot/loader/entries

# Hand freed blocks back to the disk image (disk_discard / disk_detect_zeroes =
# unmap), which also drops most of the files deleted above from the published
# image. A failed trim fails the build.
# Trim each filesystem by path, not with -a: -a skips a disk that doesn't
# advertise discard with no error, so it can trim nothing and exit 0.
# Every filesystem in the kickstart is XFS.
# Even a successful trim can't free part of a 64 KiB qcow2 cluster, so a small
# deleted file that shares a cluster with live data stays in the image.
# Overwrite anything secret before deleting it, as the host keys are above.
findmnt -rn -t xfs -o TARGET | while read -r mnt; do fstrim -v "$mnt"; done

# Last: remove the throwaway build key: use cloud-init to install per-VM keys.
# Packer keeps its current SSH connection open for the shutdown command.
rm -f /home/ansible/.ssh/authorized_keys
